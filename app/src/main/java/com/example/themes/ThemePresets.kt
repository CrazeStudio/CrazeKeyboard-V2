    fun parseHexColor(hex: String, fallback: Color): Color {
        return try {
            val clean = hex.removePrefix("#")
            when (clean.length) {
                6 -> Color(android.graphics.Color.parseColor("#FF$clean"))
                8 -> Color(android.graphics.Color.parseColor("#$clean"))
                else -> fallback
            }
        } catch (_: Exception) {
            fallback
        }
    }

    fun buildCustomTheme(bgHex: String, keyHex: String, accentHex: String, textHex: String): KeyboardTheme {
        val bg = parseHexColor(bgHex, Color(0xFF1E1E2E))
        val key = parseHexColor(keyHex, Color(0xFF313244))
        val accent = parseHexColor(accentHex, Color(0xFFCBA6F7))
        val text = parseHexColor(textHex, Color(0xFFCDD6F4))

        return KeyboardTheme(
            id = "custom",
            name = "Custom Masterpiece",
            backgroundColor = bg,
            keyColor = key,
            specialKeyColor = key.copy(alpha = 0.8f),
            accentColor = accent,
            textColor = text,
            secondaryTextColor = text.copy(alpha = 0.65f),
            borderColor = text.copy(alpha = 0.15f),
            hasBorders = true,
            elevationDp = 1.5f,
            keyCornerRadiusDp = 8f,
            isMonospace = false,
            popupColor = key,
            popupTextColor = text,
            toolbarColor = bg,
            devToolbarColor = key.copy(alpha = 0.8f)
        )
    }

    fun resolveTheme(
        id: String,
        isSystemDark: Boolean,
        customBgHex: String = "#1E1E2E",
        customKeyHex: String = "#313244",
        customAccentHex: String = "#CBA6F7",
        customTextHex: String = "#CDD6F4"
    ): KeyboardTheme {
        if (id.equals("custom", ignoreCase = true)) {
            return buildCustomTheme(customBgHex, customKeyHex, customAccentHex, customTextHex)
        }
        if (id.equals("system", ignoreCase = true)) {
            return if (isSystemDark) {
                Dark.copy(
                    id = "system",
                    name = "System Adaptive (Dark)"
                )
            } else {
                NaturalSage.copy(
                    id = "system",
                    name = "System Adaptive (Light)"
                )
            }
        }
        if (id.equals("white", ignoreCase = true)) return NaturalSage
        return allThemes.find { it.id.equals(id, ignoreCase = true) } ?: NaturalSage
    }

    fun getThemeById(id: String): KeyboardTheme {
        if (id.equals("custom", ignoreCase = true)) return buildCustomTheme("#1E1E2E", "#313244", "#CBA6F7", "#CDD6F4")
        if (id.equals("white", ignoreCase = true)) return NaturalSage
        return allThemes.find { it.id.equals(id, ignoreCase = true) } ?: NaturalSage
    }
